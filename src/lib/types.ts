export interface HeroStatus {
  k: string;
  v: string;
}

export interface Hero {
  name: string;
  thesis: string;
  affil: string;
  state: string;
  status: HeroStatus[];
}

export interface Stat {
  v: string;
  k: string;
}

export interface Education {
  d: string;
  i: string;
  p: string;
  c: string;
}

export interface Organisation {
  n: string;
  r: string;
  p: string;
}

export interface About {
  body: string;
  stats: Stat[];
  edu: Education[];
  org: Organisation[];
}

export interface Research {
  n: string;
  title: string;
  period: string;
  status: string;
  venue: string;
  doi?: string;
  stack: string[];
  summary: string;
  eq: string;
  /** Null when the repository is private; the page says so instead of linking. */
  repo: string | null;
}

/** One repository inside a project cluster. */
export interface ClusterMember {
  name: string;
  /** What this member does inside the cluster, in one line. */
  role: string;
  stack: string;
  status: string;
  /** Null when the repository is private. */
  repo: string | null;
  site?: string;
  doi?: string;
  /** Collaborators, shown as "w/ ...". */
  attr?: string;
  /** Which specimen figure to draw for this repository. */
  fig: "circuit" | "simplex" | "spectrum" | "landscape" | "pages" | "window" | "phone" | "plates" | "biomes";
}

/** A group of related repositories, shown as one plate under Selected Works. */
export interface Cluster {
  name: string;
  sub: string;
  desc: string;
  cat: string;
  members: ClusterMember[];
}

export interface IndexProject {
  name: string;
  cat: string;
  status: string;
  year: string;
  stack: string;
  repo: string | null;
  doi?: string;
  attr?: string;
}

export interface NotebookEntry {
  date: string;
  tag: string;
  title: string;
  body: string;
}

export interface Currently {
  k: string;
  v: string;
}

/**
 * Commit counts for one public repo, generated by
 * scripts/generate-activity.mjs and written to src/lib/activity.json.
 * Never hand-edited.
 */
export interface ActivityRepo {
  repo: string;
  /** Commits per week, oldest first, aligned to ActivitySnapshot.weeks. */
  weeks: number[];
  total: number;
}

export interface ActivitySnapshot {
  /** ISO timestamp of the run that produced this file. */
  generated: string;
  /** Week labels, oldest first, e.g. ["Jul 14", ...]. */
  weeks: string[];
  repos: ActivityRepo[];
}

export interface Cert {
  n: string;
  i: string;
  d: string | null;
  l: string | null;
}

export interface Patent {
  id: string;
  title: string;
  filed: string;
  office: string;
}
